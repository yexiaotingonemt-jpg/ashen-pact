export function cardInfo(instance) {
  const base = CARDS[instance.key];
  if (!instance.upgraded) return base;
  const c = { ...base, name: base.name + "⁺" };
  if (c.contractEffect) {
    c.cost = Math.max(0, c.cost - 1);
    return c;
  }
  if (c.type === "unit") {
    c.atk++;
    c.hp += 2;
  } else if (c.damage) c.damage += 3;
  else if (c.armor) c.armor += 4;
  else if (c.heal) c.heal += 4;
  else if (c.aoe) c.aoe += 2;
  else if (c.draw) c.draw++;
  else if (c.buff) c.buff++;
  else if (c.energy) c.energy++;
  c.text =
    c.type === "unit"
      ? base.text
      : c.damage
        ? `造成 ${c.damage} 点伤害。${c.burn ? "附加 3 层灼烧。" : instance.key === "bolt" ? "击杀目标时，抽 1 张牌。" : ""}`
        : c.armor
          ? `获得 ${c.armor} 点护甲。护甲可跨回合保留。`
          : c.heal
            ? `恢复 ${c.heal} 点生命。${c.draw ? "抽 1 张牌。" : ""}`
            : c.aoe
              ? `对所有敌方随从造成 ${c.aoe} 点伤害。`
              : c.buff
                ? `使一个友方随从获得 +${c.buff}/+${c.buff}，并恢复全部生命。`
                : c.draw
                  ? `抽 ${c.draw} 张牌。`
                  : `本回合获得 ${c.energy} 点能量。消耗。`;
  if (c.debt && c.type === "spell") {
    c.text = c.damage
      ? `对一个敌人造成 ${c.damage} 点伤害。`
      : c.armor
        ? `立即获得 ${c.armor} 点护甲。`
        : c.draw
          ? `立即抽 ${c.draw} 张牌。`
          : `本回合获得 ${c.energy} 点能量。消耗。`;
  }
  return c;
}

